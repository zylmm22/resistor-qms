function requiredRule(label, type, section) {
  if (section === '基本信息' || /项目名称|零件号|型号|编制|日期/.test(label)) return '必填/自动引用';
  if (/审核|会签|批准/.test(label)) return '条件必填（审批时）';
  if (/备注|说明|补充|其他/.test(label)) return '选填';
  if (type === 'table' || type === 'table-column') return '至少一行（适用时）';
  return '条件必填（项目适用时）';
}

function genericRule(label, type) {
  for (const [pattern, guidance, source] of RULES) {
    if (pattern.test(label)) return { guidance, source };
  }
  if (type === 'table' || type === 'table-column') {
    for (const [pattern, guidance, source] of COLUMN_RULES) {
      if (pattern.test(label)) return { guidance, source };
    }
  }
  if (type === 'table' || type === 'table-column') {
    return {
      guidance: `填写“${label}”对应的项目事实、依据和结论；内容应可核对，不能只在备注中写“已确认”。`,
      source: '受控项目记录',
    };
  }
  if (type === 'textarea') {
    return {
      guidance: '写清范围、依据、事实和结论，避免只写“已确认”或“符合要求”。',
      source: '受控项目记录',
    };
  }
  if (type === 'select') {
    return {
      guidance: '只能从允许值中选择；不适用时按系统规则说明理由。',
      source: '受控项目记录',
    };
  }
  return {
    guidance: '填写可核验的业务事实，并保留来源文件或记录。',
    source: '受控项目记录',
  };
}

function buildGuide(code, section, label, type) {
  const specific = SPECIFIC[`${code}:${label}`] || {};
  const generic = genericRule(label, type);
  return {
    label,
    required: requiredRule(label, type, section),
    guidance: specific.guidance || generic.guidance,
    source: specific.source || generic.source,
    example: EXAMPLES[`${code}:${label}`] || '',
    exampleLabel: EXAMPLES[`${code}:${label}`] ? '历史项目示例' : '',
    missing: '无法追溯的内容保持空白并标记待确认，不得用“无”“合格”或 0 占位。',
  };
}

function forField(code, section, field) {
  const type = field.type === 'table' ? 'table-column' : field.type;
  return buildGuide(code, section, field.label, type);
}

function forColumn(code, section, field, label, index) {
  return {
    ...buildGuide(code, section, label, 'table-column'),
    columnKey: field.k,
    index,
  };
}

module.exports = { forField, forColumn };
